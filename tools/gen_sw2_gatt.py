"""Generate the discovery-stage Telink table from the documented fixed handles.

Writes are deliberately consumed by a callback: flash-backed values must never
be passed to the stock default write/memcpy path. No pairing is implemented here.
"""
from pathlib import Path
from uuid import UUID


def generate():
    definitions = []
    entries = ['{59,0,0,0,0,0,0,0}']

    def blob(data):
        name = 'gatt_data_%d' % len(definitions)
        definitions.append('static const u8 %s[] = {%s};' %
                           (name, ','.join('0x%02x' % b for b in data)))
        return name

    def uuid(value):
        return value.to_bytes(2, 'little') if isinstance(value, int) else UUID(value).bytes[::-1]

    def attr(kind, value, perm=1, count=0):
        uid = uuid(kind)
        up, vp = blob(uid), blob(value or b'\0')
        if len(entries)==0x26:
            vp='(const u8 *)SW2_DEBUG'
            value=bytes(8)
        cccds=(0xb,0xf,0x1b,0x1f,0x23,0x27,0x2f,0x3b)
        if len(entries) in cccds:
            vp='(const u8 *)(CCCD+%d)' % (2*cccds.index(len(entries)))
        cb = 'sw2_discovery_write' if perm & 2 else '0'
        entries.append('{%d,%d,%d,%d,%s,%s,%s,0}' %
                       (count, perm, len(uid), len(value), up, vp, cb))

    def service(uid, count):
        attr(0x2800, uuid(uid), count=count)

    def char(handle, uid, props, value=b'\0', desc=None):
        assert len(entries) == handle - 1, (len(entries), handle)
        attr(0x2803, bytes([props, handle, 0]) + uuid(uid))
        attr(uid, value, (1 if props & 2 else 0) | (2 if props & 12 else 0))
        if props & 16:
            attr(0x2902, b'\0\0', 3)
            attr(desc, b'\0\0', 3)

    svc1 = '00c5af5d-1964-4e30-8f51-1956f96bd28'
    svc2 = 'ab7de9be-89fe-49ad-828f-118f09df7fd'
    rate = '679d5510-5a24-4dee-9557-95df80486ecb'
    other = 'b746df8c-f358-495b-9cd2-e3bbeda4f979'
    service(svc1+'0', 7)
    char(3, svc1+'1', 2, bytes.fromhex('04000500010100'))
    char(5, svc1+'2', 8, b'\0\0')
    char(7, svc1+'3', 2, bytes.fromhex('368074eebb3d8e13'))
    service(svc2+'0', 43)
    char(0x0a, svc2+'2', 18, bytes(32), rate)
    char(0x0e, '7492866c-ec3e-4619-8258-32755ffcc0f8', 18, bytes(63), rate)
    for h, uid in [(0x12,'cc483f51-9258-427d-a939-630c31f72b05'),
                   (0x14,'649d4ac9-8eb7-4e6c-af44-1ea54fe5f005'),
                   (0x16,'3dacbc7e-6955-40b5-8eaf-6f9809e8b379'),
                   (0x18,'4147423d-fdae-4df7-a4f7-d23e5df59f8d')]:
        char(h, uid, 4)
    char(0x1a,'c765a961-d9d8-4d36-a20a-5315b111836a',16,desc=other)
    char(0x1e,'506d9f7d-4278-4e95-a549-326ba77657e0',16,desc=other)
    char(0x22,'d3bd69d2-841c-4241-ab15-f86f406d2a80',16,desc=other)
    char(0x26,svc2+'e',18,desc=rate)
    char(0x2a,svc2+'f',4)
    char(0x2c,'cc483f51-9258-427d-a939-630c31f72b06',4)
    char(0x2e,'7492866c-ec3e-4619-8258-32755ffcc0f9',18,desc=rate)
    char(0x32,'3dacbc7e-6955-40b5-8eaf-6f9809e8b380',4)
    service(0x1800,5)
    char(0x35,0x2a00,2,b'Pro Controller')
    char(0x37,0x2a01,2,b'\xc4\x03')
    # Stock group-end finder returns zero for a service at the very last
    # handle. The empty 0x38 service caused repeated (0x38,0) pairs on air.
    # Keep all Nintendo handles and append standard Service Changed, as espp does.
    service(0x1801,4)
    char(0x3a,0x2a05,0x20,bytes(4))
    attr(0x2902,b'\0\0',3)
    assert len(entries) == 60
    return ('/* Generated by tools/gen_sw2_gatt.py; do not edit. */\n' +
            '\n'.join(definitions) + '\nstatic const Sw2Attribute sw2_attributes[] = {\n' +
            ',\n'.join('    '+e for e in entries) + '\n};\n')


if __name__ == '__main__':
    Path('src/sw2/gatt.inc').write_text(generate(), encoding='ascii')
