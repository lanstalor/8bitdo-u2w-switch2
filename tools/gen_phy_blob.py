"""Generate the RAM overlay include from the linked TC32 image (run during build)."""
import pathlib
import subprocess

root = pathlib.Path(__file__).resolve().parents[1] / 'src' / 'sw2'
subprocess.run(['tc32-elf-objcopy', '-O', 'binary', '--only-section=.text',
                str(root / 'phy_ram.elf'), str(root / 'phy_ram.bin')], check=True)
blob = (root / 'phy_ram.bin').read_bytes()
assert 0 < len(blob) <= 352
symbols = subprocess.check_output(['tc32-elf-nm', '-n', str(root / 'phy_ram.elf')], text=True)
entries = {line.split()[2]: int(line.split()[0], 16) for line in symbols.splitlines()
           if len(line.split()) == 3}
lines = ['/* Generated by tools/gen_phy_blob.py; see phy_ram.c for provenance. */']
for name in ('sw2_radio_phy', 'sw2_phy_instant', 'sw2_phy_start'):
    assert 0xc04 <= entries[name] < 0xc04 + len(blob)
    lines.append(f'#define {name.upper()}_ADDR 0x{entries[name]:x}u')
lines.append('static const u8 sw2_phy_blob[] = {')
for offset in range(0, len(blob), 16):
    lines.append('    ' + ','.join(f'0x{x:02x}' for x in blob[offset:offset+16]) + ',')
lines.append('};')
(root / 'phy_blob.inc').write_text('\n'.join(lines) + '\n')
